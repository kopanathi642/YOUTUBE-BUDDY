"""Regenerate docs/DUBBING_LANGUAGES.md from app/speech/catalog.py:  python scripts/gen_language_doc.py > ../docs/DUBBING_LANGUAGES.md"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from app.speech import assets, catalog  # noqa: E402

L = catalog.LANG_NAMES
print("# Dubbing languages — exact list (generated by `backend/scripts/gen_language_doc.py` from `app/speech/catalog.py`)\n")
print("Self-hosted only (no paid API, ₹0 per dub): Whisper speech-to-text → Argos translation → Kokoro/Piper voices. "
      "A language appears in the app only when every model on its path is pinned, downloaded and verified on the worker. "
      "Measured quality per language: `DUBBING_EVAL.md`.\n")
print(f"## Source languages ({len(catalog.SOURCE_LANGS)}): what you can dub FROM\n")
print("Detected automatically (or chosen by hand). Whisper recognises ~100 languages, but only these can be translated:\n")
print(", ".join(f"{L.get(c, c)} (`{c}`)" for c in catalog.SOURCE_LANGS) + "\n")
print(f"## Target languages ({len(catalog.TARGET_LANGS)}): what you can dub INTO, with voices\n")
print("| Language | Code | Translation from English | Voices (engine · licence) |\n|---|---|---|---|")
for t in catalog.TARGET_LANGS:
    vs = catalog.voices_for(t)
    code = catalog.ARGOS_TARGET_CODE.get(t, t)
    route = "—" if t == "en" else f"Argos en→{code} {catalog.ARGOS_FROM_EN[code]}"
    print(f"| {L.get(t, t)} | `{t}` | {route} | " + "; ".join(f"{v['label']} ({v['engine']} · {v['licence']})" for v in vs) + " |")
print("\n## Dialects and accents (as the voices actually speak)\n")
print("- English: American (Heart, Michael, Nicole) and British (George, Emma). Speech recognition handles Indian English.")
print("- Portuguese: Brazilian only (both voices are pt-BR; translation uses the Brazilian model).")
print("- Spanish: Castilian-style voices (Kokoro); speech recognition handles Latin American Spanish (FLEURS es-419 WER 3.7%).")
print("- Dutch: Netherlands (Pim) and Flemish (Nathalie). Norwegian: Bokmål.")
print("- Hindi: standard Hindi voices. Spoken Hindi is often scored as Urdu by Whisper; the app folds Urdu into Hindi when Hindi has a real chance (`ASR_PREFER`, default `ur:hi:0.10`).\n")
print("## Every source → target pair\n")
print(f"{len(catalog.SOURCE_LANGS)} × {len(catalog.TARGET_LANGS)} = {len(catalog.SOURCE_LANGS) * len(catalog.TARGET_LANGS)} combinations, all routed. "
      "Pairs without English on one side go through English (two translation steps: expect lower quality). Same-language pairs only re-voice. "
      "The server reports the route of every pair at `GET /api/v1/dub/languages`.\n")
print("## Mixed-language speech\n")
print("The file's language is detected from up to six 15-second windows across the whole file (not just the start). Then **every sentence of ≥ 1.2 s "
      "gets its own language check**; if Whisper is ≥ 70 % sure it is another language, that sentence is re-recognised in its own language and marked. "
      "Translation works sentence by sentence from each sentence's real language; sentences already in the target language are kept. "
      "Users can correct any sentence's language (and the whole file's language) in the studio.\n")
print("## Not available (and why)\n")
print("| Languages | Why |\n|---|---|")
print("| Japanese, Chinese (as targets) | Kokoro voices failed the pronunciation check (judge CER 309 % and 60 %): kokoro-onnx's espeak phonemizer can't read them. Needs the misaki ja/zh phonemizer. Still available as **sources**. |")
print("| Tamil, Telugu, Marathi, Kannada, Gujarati, Malayalam, Punjabi, Odia | No commercially usable free translation model in the pinned set (Whisper recognises their speech, but it can't be translated); Malayalam Piper voices have an unclear licence. Path: AI4Bharat IndicTrans2 (MIT) + Indic Parler-TTS (Apache-2.0), see FINE_TUNING_PLAN.md §2 |")
print("| Bengali, Urdu, Arabic, Korean, Thai, Indonesian, Hebrew… (as targets) | Can be dubbed FROM, but no commercially licensed voice exists for them in Kokoro/Piper |")
print("| Hindi Piper voices Pratham and Priyamvada | Licence CC BY-NC-SA 4.0 (non-commercial) — replaced by Kokoro Hindi voices (Apache-2.0) |")
print("| English Piper voices Ryan, Lessac, Amy, HFC | Non-commercial or unclear licences — replaced by Kokoro English voices |")
print("| Automatic speaker separation of overlapping speech | One speaker per sentence only; users can relabel any sentence |")
print("| Removing the original voice under the dub | No source-separation model: the original track is lowered to 15 % during speech (`duck`, 0 = mute) |")
lock = assets._load_lock()
tot = sum(v["size"] for k, v in lock.items() if not k.startswith("whisper-medium") and k not in ("argos/en_ja", "argos/en_zh"))
print(f"\n## Disk and memory\n\nAll languages with Whisper small: **~{tot / 1e9:.1f} GB** on the worker's model disk (`DUB_SOURCES` / `DUB_TARGETS` narrow it; "
      "Whisper medium adds 1.5 GB). Peak RAM while dubbing and timings: `DUBBING_EVAL.md`; models are released after each job.")
